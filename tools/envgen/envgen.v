module main

import os

// Writes build_remote.v with the backend address Cube Watch connects to,
// taken from .env (see .env.example):
//
//   REMOTE_ADDR=host:port     the backend (server/); empty = do not connect.
//                             Behind HTTPS (nginx, Caddy, ...): the host name
//                             alone or wss://host - see wire.parse_endpoint
//   REMOTE_KEY=...            its --client-key, if it has one
//
// build.bat runs it before every compile, so the address is fixed in the
// executable. Only these two values are read from .env.

fn value_of(lines []string, name string) string {
	for line in lines {
		key, value := line.split_once('=') or { continue }
		if key.trim_space() == name {
			return value.trim_space().trim('"\'')
		}
	}
	return ''
}

// v_string writes a value as a V string literal.
fn v_string(s string) string {
	return "'" + s.replace_each(['\\', '\\\\', "'", "\\'", '$', '\\$', '\r', '', '\n', '']) + "'"
}

fn main() {
	out := if os.args.len > 1 { os.args[1] } else { 'build_remote.v' }
	env := if os.args.len > 2 { os.args[2] } else { '.env' }
	lines := os.read_lines(env) or { []string{} }
	addr := value_of(lines, 'REMOTE_ADDR')
	key := value_of(lines, 'REMOTE_KEY')
	src := '// Generated by tools/envgen from .env at build time. Do not edit or commit.
module main

const remote_addr = ${v_string(addr)}
const remote_key = ${v_string(key)}
'
	os.write_file(out, src) or {
		eprintln('envgen: ${err}')
		exit(1)
	}
	println(if addr == '' {
		'Backend: none (REMOTE_ADDR is not set in ${env})'
	} else {
		'Backend: ${addr}' + if key == '' { ' (no client key)' } else { ' (with a client key)' }
	})
}
